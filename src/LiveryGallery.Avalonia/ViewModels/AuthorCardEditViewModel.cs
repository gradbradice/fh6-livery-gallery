using CommunityToolkit.Mvvm.ComponentModel;
using CommunityToolkit.Mvvm.Input;
using LiveryGallery.Localisation;
using LiveryGallery.Services;
using System.Collections.ObjectModel;
using System.Globalization;

namespace LiveryGallery.ViewModels;

internal sealed partial class AuthorCardEditViewModel : ObservableObject
{
    private readonly AuthorCardService _authorCardService;
    private readonly string? _editingCardId;
    // A card made on the fly for an account (not saved yet): saving gives it an id of its own
    private readonly bool _editingImplicit;
    // Oldest first: the last one is the name the card shows, so the list of accounts must not reorder them
    private readonly IReadOnlyList<string> _existingNames;

    public string Title { get; }
    public bool ShowAutoGeneratedNotice { get; }

    /// <summary>The accounts the card may take, oldest first; two accounts of one name are two rows</summary>
    public ObservableCollection<AccountCheckboxViewModel> AvailableAccounts { get; } = [];

    [ObservableProperty]
    private string _accountSearchText = "";

    [ObservableProperty]
    private string? _customName;

    [ObservableProperty]
    private string? _description;

    [ObservableProperty]
    private string? _twitterUrl;

    [ObservableProperty]
    private string? _youTubeUrl;

    [ObservableProperty]
    private string? _twitchUrl;

    [ObservableProperty]
    private bool _hasAccountsError;
    [ObservableProperty]
    private string? _accountsErrorText;

    [ObservableProperty]
    private bool _hasCustomNameError;
    [ObservableProperty]
    private string? _customNameErrorText;

    [ObservableProperty]
    private bool _hasTwitterError;
    [ObservableProperty]
    private string? _twitterErrorText;

    [ObservableProperty]
    private bool _hasYouTubeError;
    [ObservableProperty]
    private string? _youTubeErrorText;

    [ObservableProperty]
    private bool _hasTwitchError;
    [ObservableProperty]
    private string? _twitchErrorText;
    public event Action<bool>? CloseRequested;

    public AuthorCard? Result { get; private set; }

    /// <param name="authorCardService">The cards</param>
    /// <param name="accounts">The accounts the card may take (<see cref="AuthorContext.LabelAccounts"/>)</param>
    /// <param name="existingCard">The card being edited; null for a new one</param>
    public AuthorCardEditViewModel(
        AuthorCardService authorCardService, IReadOnlyList<AuthorAccountChoice> accounts, AuthorCard? existingCard)
    {
        _authorCardService = authorCardService;
        _editingCardId = existingCard?.Id;
        _editingImplicit = existingCard is { IsImplicit: true };
        _existingNames = existingCard?.KnownNames ?? [];

        Title = existingCard is null or { IsImplicit: true } ? Strings.AuthorCardNewTitle : Strings.AuthorCardEditTitle;
        ShowAutoGeneratedNotice = existingCard is { IsAutoGenerated: true };
        var selectedTags = existingCard?.IdentityTags.ToHashSet(StringComparer.OrdinalIgnoreCase)
            ?? new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var account in accounts)
            AvailableAccounts.Add(new AccountCheckboxViewModel(account) { IsSelected = selectedTags.Contains(account.Option.IdentityTag) });

        if (existingCard is not null)
        {
            CustomName = existingCard.CustomName;
            Description = existingCard.Description;
            TwitterUrl = existingCard.TwitterUrl;
            YouTubeUrl = existingCard.YouTubeUrl;
            TwitchUrl = existingCard.TwitchUrl;
        }
    }

    partial void OnAccountSearchTextChanged(string value)
    {
        foreach (var account in AvailableAccounts)
            account.IsVisible = string.IsNullOrWhiteSpace(value) || account.Matches(value);
    }

    [RelayCommand]
    private void Save()
    {
        ClearErrors();
        bool hasError = false;

        var selected = AvailableAccounts.Where(a => a.IsSelected).ToList();
        var selectedTags = selected.Select(a => a.IdentityTag).Distinct(StringComparer.OrdinalIgnoreCase).ToList();
        // The names: the card's own ones stay unless they came only with an account the user took off; the names of
        // the accounts it took come after them, oldest first
        var namesOfSelected = selected.SelectMany(a => a.Names).ToHashSet(StringComparer.OrdinalIgnoreCase);
        var namesOfDropped = AvailableAccounts.Where(a => !a.IsSelected).SelectMany(a => a.Names)
            .Where(n => !namesOfSelected.Contains(n)).ToHashSet(StringComparer.OrdinalIgnoreCase);
        var knownNames = _existingNames
            .Where(n => !namesOfDropped.Contains(n))
            .Concat(selected.SelectMany(a => a.Names).Where(n => !_existingNames.Contains(n, StringComparer.OrdinalIgnoreCase)))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .ToList();

        // A card may start without an account: the user knows the author, not the account yet. Then it needs a name
        if (selectedTags.Count == 0 && knownNames.Count == 0 && string.IsNullOrWhiteSpace(CustomName))
        {
            HasAccountsError = true;
            AccountsErrorText = Strings.AuthorCardNoAliasesOrNameError;
            hasError = true;
        }
        else
        {
            string? conflicting = _authorCardService.FindConflictingIdentityTag(_editingCardId, selectedTags);
            if (conflicting is not null)
            {
                HasAccountsError = true;
                string label = AvailableAccounts.FirstOrDefault(a => string.Equals(a.IdentityTag, conflicting, StringComparison.OrdinalIgnoreCase))?.Label ?? conflicting;
                AccountsErrorText = string.Format(AppLocalisationService.Culture, Strings.AuthorCardAliasTakenError, label);
                hasError = true;
            }
        }

        string? twitterUrl = NormalizeUrl(TwitterUrl);
        if (twitterUrl is not null && !IsValidTwitterUrl(twitterUrl))
        {
            HasTwitterError = true;
            TwitterErrorText = Strings.AuthorCardInvalidTwitterUrlError;
            hasError = true;
        }

        string? youTubeUrl = NormalizeUrl(YouTubeUrl);
        if (youTubeUrl is not null && !IsValidYouTubeChannelUrl(youTubeUrl))
        {
            HasYouTubeError = true;
            YouTubeErrorText = Strings.AuthorCardInvalidYouTubeUrlError;
            hasError = true;
        }

        string? twitchUrl = NormalizeUrl(TwitchUrl);
        if (twitchUrl is not null && !IsValidTwitchChannelUrl(twitchUrl))
        {
            HasTwitchError = true;
            TwitchErrorText = Strings.AuthorCardInvalidTwitchUrlError;
            hasError = true;
        }

        if (knownNames.Count > 0 || !string.IsNullOrWhiteSpace(CustomName))
        {
            // The same rule as AuthorCard.DisplayName: the custom name, otherwise the latest known name
            var candidateName = string.IsNullOrWhiteSpace(CustomName) ? knownNames[^1] : CustomName.Trim();
            var nameConflict = _authorCardService.FindCardWithDisplayName(_editingCardId, candidateName, selectedTags);
            if (nameConflict is not null)
            {
                HasCustomNameError = true;
                CustomNameErrorText = string.Format(Strings.AuthorCardDisplayNameTakenError, candidateName);
                hasError = true;
            }
        }

        if (hasError) return;

        Result = new AuthorCard
        {
            Id = _editingCardId is null || _editingImplicit ? Guid.NewGuid().ToString("N") : _editingCardId,
            IdentityTags = selectedTags,
            KnownNames = knownNames,
            CustomName = string.IsNullOrWhiteSpace(CustomName) ? null : CustomName.Trim(),
            Description = string.IsNullOrWhiteSpace(Description) ? null : Description.Trim(),
            TwitterUrl = twitterUrl,
            YouTubeUrl = youTubeUrl,
            TwitchUrl = twitchUrl,
            IsAutoGenerated = false,
        };
        CloseRequested?.Invoke(true);
    }

    [RelayCommand]
    private void Cancel() => CloseRequested?.Invoke(false);

    private void ClearErrors()
    {
        HasAccountsError = false;
        HasCustomNameError = false;
        HasTwitterError = false;
        HasYouTubeError = false;
        HasTwitchError = false;
    }

    private static string? NormalizeUrl(string? url)
    {
        if (string.IsNullOrWhiteSpace(url)) return null;
        url = url.Trim();
        return url.Contains("://", StringComparison.Ordinal) ? url : $"https://{url}";
    }

    private static bool IsValidTwitterUrl(string url)
    {
        if (!Uri.TryCreate(url, UriKind.Absolute, out var uri)) return false;
        string host = uri.Host.ToLowerInvariant();
        if (!TrustedUrlLauncher.TwitterHosts.Contains(host, StringComparer.OrdinalIgnoreCase))
            return false;

        string[] segments = uri.AbsolutePath.Trim('/').Split('/', StringSplitOptions.RemoveEmptyEntries);
        if (segments.Length != 1) return false;

        string username = segments[0].ToLowerInvariant();
        return username is not (
            "home" or "explore" or "notifications" or "messages" or "search" or "settings"
            or "i" or "intent" or "hashtag" or "share" or "login" or "signup" or "compose" or "about");
    }

    private static bool IsValidYouTubeChannelUrl(string url)
    {
        if (!Uri.TryCreate(url, UriKind.Absolute, out var uri)) return false;
        string host = uri.Host.ToLowerInvariant();
        if (!TrustedUrlLauncher.YouTubeHosts.Contains(host, StringComparer.OrdinalIgnoreCase)) return false;

        string path = uri.AbsolutePath.TrimStart('/');
        return (path.StartsWith('@') && path.Length > 1)
            || HasNonEmptySuffix(path, "channel/")
            || HasNonEmptySuffix(path, "c/")
            || HasNonEmptySuffix(path, "user/");
    }

    /// <summary>A Twitch channel: twitch.tv/name (4–25 letters, digits or underscores), not a page of the site itself</summary>
    internal static bool IsValidTwitchChannelUrl(string url)
    {
        if (!Uri.TryCreate(url, UriKind.Absolute, out var uri)) return false;
        if (!TrustedUrlLauncher.TwitchHosts.Contains(uri.Host, StringComparer.OrdinalIgnoreCase)) return false;

        string[] segments = uri.AbsolutePath.Trim('/').Split('/', StringSplitOptions.RemoveEmptyEntries);
        if (segments.Length != 1) return false;
        string name = segments[0];
        if (name.Length is < 4 or > 25 || !name.All(c => char.IsAsciiLetterOrDigit(c) || c == '_')) return false;
        return name.ToLowerInvariant() is not (
            "directory" or "videos" or "search" or "settings" or "subscriptions" or "inventory" or "wallet" or "drops"
            or "friends" or "messages" or "login" or "signup" or "downloads" or "jobs" or "store" or "prime" or "turbo");
    }

    private static bool HasNonEmptySuffix(string path, string prefix) =>
        path.StartsWith(prefix, StringComparison.OrdinalIgnoreCase) && path.Length > prefix.Length;
}
