using Avalonia.Controls;
using Avalonia.Input;
using LiveryGallery.Localisation;
using LiveryGallery.Services;
using LiveryGallery.ViewModels;

namespace LiveryGallery.Views;

internal partial class AuthorCardEditDialog : Window
{
    private readonly AuthorCardEditViewModel _viewModel;

    public AuthorCard? Result => _viewModel.Result;

    public AuthorCardEditDialog(
        AuthorCardService authorCardService, IReadOnlyList<AuthorAccountChoice> accounts, AuthorCard? existingCard)
    {
        InitializeComponent();
        _viewModel = new AuthorCardEditViewModel(authorCardService, accounts, existingCard);
        DataContext = _viewModel;
        _viewModel.CloseRequested += saved => Close(saved);

        Title = _viewModel.Title;
        TitleBarText.Text = _viewModel.Title;
        TitleText.Text = _viewModel.Title;
        AutoGeneratedNotice.Text = Strings.AuthorCardAutoGeneratedNotice;
        AccountsLabel.Text = Strings.AuthorCardAliasesLabel;
        AccountsHint.Text = Strings.AuthorCardAliasesHint;
        AccountSearchBox.PlaceholderText = Strings.AuthorCardAliasSearchPlaceholder;
        CustomNameLabel.Text = Strings.AuthorCardCustomNameLabel;
        CustomNameBox.PlaceholderText = Strings.AuthorCardCustomNameHint;
        DescriptionLabel.Text = Strings.AuthorCardDescriptionLabel;
        TwitterLabel.Text = Strings.AuthorCardTwitterLabel;
        YouTubeLabel.Text = Strings.AuthorCardYouTubeLabel;
        TwitchLabel.Text = Strings.AuthorCardTwitchLabel;
        SaveButton.Content = Strings.ButtonSave;
        CancelButton.Content = Strings.ButtonCancel;
    }

    private void TitleBar_PointerPressed(object? sender, PointerPressedEventArgs e) => this.HandleTitleBarDrag(e);
}
