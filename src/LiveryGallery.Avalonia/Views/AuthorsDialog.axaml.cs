using Avalonia.Controls;
using Avalonia.Input;
using LiveryGallery.Localisation;
using LiveryGallery.ViewModels;

namespace LiveryGallery.Views;

internal partial class AuthorsDialog : Window
{
    private readonly AuthorCardService _authorCardService;
    private readonly AuthorsViewModel _viewModel;
    private readonly DialogWorkScope _work;

    public AuthorsDialog(AuthorCardService authorCardService, List<LiveryEntry> allEntries, Func<Task<List<LiveryEntry>>> refreshEntries)
    {
        InitializeComponent();
        _authorCardService = authorCardService;
        _viewModel = new AuthorsViewModel(authorCardService, allEntries, refreshEntries);
        DataContext = _viewModel;

        _work = new DialogWorkScope(this);
        _viewModel.EditCardRequested += existingCard => _work.Run(() => EditCardAsync(existingCard), "authors: edit card");
        _viewModel.DeleteCardRequested += row => _work.Run(() => DeleteCardAsync(row), "authors: delete card");
        _viewModel.MergeRequested += (cardIds, extraTags, names) =>
            _work.Run(() => MergeAsync(cardIds, extraTags, names), "authors: merge cards");
        _viewModel.SplitRequested += row => _work.Run(() => SplitAsync(row), "authors: split card");

        Title = Strings.AuthorsDialogTitle;
        TitleBarText.Text = Strings.AuthorsDialogTitle;
        TitleText.Text = Strings.AuthorsDialogTitle;
        AddCardButton.Content = Strings.AuthorsAddCardButton;
        SearchBox.PlaceholderText = Strings.AuthorsSearchPlaceholder;
    }

    private void TitleBar_PointerPressed(object? sender, PointerPressedEventArgs e) => this.HandleTitleBarDrag(e);

    private async Task EditCardAsync(AuthorCard? existingCard)
    {
        var dialog = new AuthorCardEditDialog(_authorCardService, _viewModel.AccountChoices(existingCard?.Id), existingCard);
        bool saved = await dialog.ShowDialog<bool>(this);
        if (!saved || dialog.Result is null) return;

        await _viewModel.TrySaveCard(dialog.Result);
    }

    private async Task DeleteCardAsync(AuthorCardRowViewModel row)
    {
        // An automatic card is hidden rather than deleted, or the next scan would create it again
        string message = string.Format(
            row.IsAutoGenerated ? Strings.AuthorCardHideAutoMessage : Strings.AuthorCardDeleteMessage, row.DisplayName);
        bool confirmed = await ConfirmDialog.AskAsync(this, Strings.AuthorCardDeleteTitle, message);
        if (!confirmed) return;

        await _viewModel.DeleteCardAsync(row.Card.Id);
    }

    private async Task MergeAsync(IReadOnlyList<string> cardIds, IReadOnlyList<string> extraTags, string names)
    {
        bool confirmed = await ConfirmDialog.AskAsync(
            this, Strings.AuthorsMergeConfirmTitle, string.Format(Strings.AuthorsMergeConfirmMessage, names));
        if (!confirmed) return;

        var merged = await _viewModel.MergeAsync(cardIds, extraTags);
        if (merged is null)
        {
            await InfoDialog.ShowAsync(this, Strings.AuthorsMergeConfirmTitle, Strings.AuthorsMergeFailedMessage);
            return;
        }

        // A chance to pick the name and the links of the joined card right away
        await EditCardAsync(merged);
    }

    private async Task SplitAsync(AuthorCardRowViewModel row)
    {
        bool confirmed = await ConfirmDialog.AskAsync(
            this, Strings.AuthorCardSplitConfirmTitle, string.Format(Strings.AuthorCardSplitConfirmMessage, row.DisplayName));
        if (!confirmed) return;

        await _viewModel.SplitAsync(row);
    }

    private void CloseButton_Click(object? sender, Avalonia.Interactivity.RoutedEventArgs e) => Close();
}
