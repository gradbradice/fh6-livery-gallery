namespace LiveryGallery.Views;

/// <summary>What the author window may do besides showing the card</summary>
/// <param name="Edit">Opens the card editor over the window; the saved card, or null when cancelled</param>
/// <param name="Entries">The liveries as they are now (they change after an edit)</param>
/// <param name="Unassign">Takes a livery (by its file's hash) out of the card</param>
/// <param name="AccountHints">Accounts that may be the author's, for a card without an account</param>
/// <param name="AddAccount">Adds an account to the card (a hint accepted); the saved card, or null</param>
/// <param name="DismissHint">The user says a hint is wrong</param>
/// <param name="FindCard">The card as saved now, by id</param>
/// <param name="Statistics">The numbers of the author's liveries (the statistics window's authors' table row)</param>
internal sealed record AuthorCardViewActions(
    Func<Window, AuthorCard, Task<AuthorCard?>> Edit,
    Func<IReadOnlyList<LiveryEntry>> Entries,
    Func<string, Task> Unassign,
    Func<AuthorCard, IReadOnlyList<AuthorHintView>> AccountHints,
    Func<AuthorCard, string, Task<AuthorCard?>> AddAccount,
    Func<AuthorHint, Task> DismissHint,
    Func<string, AuthorCard?> FindCard,
    Func<IReadOnlyList<LiveryEntry>, AuthorStatisticsRow?>? Statistics = null);

/// <summary>
/// An author's card and statistics. Every account has one: a card nobody saved yet is made on the fly and written only
/// when the user changes it ("Edit"). The numbers are those of the statistics window (ForzaToolkit.Liveries
/// <c>Statistics</c>): liveries, cars, favorites, artworks moved to other cars, first seen and latest, the makes and
/// the downloads by month. Lists the liveries the user assigned to it and, for a card without an account, the accounts
/// that may be the author's.
/// </summary>
internal partial class AuthorCardViewDialog : Window
{
    private readonly AuthorCardViewActions _actions;
    private readonly DialogWorkScope _work;
    private AuthorCard _card;

    public AuthorCardViewDialog(AuthorCard card, AuthorCardViewActions actions)
    {
        InitializeComponent();
        _card = card;
        _actions = actions;
        _work = new DialogWorkScope(this);
        OkButton.Content = Strings.ButtonOk;
        EditButton.Content = Strings.ButtonEdit;
        Rebuild();
    }

    private void Rebuild()
    {
        var card = _card;
        var allEntries = _actions.Entries();
        Title = card.DisplayName;
        TitleBarText.Text = card.DisplayName;
        ContentPanel.Children.Clear();

        var tagSet = card.IdentityTags.ToHashSet(StringComparer.OrdinalIgnoreCase);
        var authorEntries = allEntries
            .Where(e => e.AssignedCardId == card.Id
                || (e.AssignedCardId is null && e.AuthorIdentityTagHex is not null && tagSet.Contains(e.AuthorIdentityTagHex)))
            .ToList();

        ContentPanel.Children.Add(new TextBlock
        {
            Text = card.DisplayName,
            FontSize = 18,
            FontWeight = FontWeight.Bold,
        });

        string? badge = card.IsImplicit ? Strings.AuthorCardImplicitNotice
            : card.IsAutoGenerated ? Strings.AuthorCardAutoGeneratedBadge
            : null;
        if (badge is not null) ContentPanel.Children.Add(Note(badge, "AccentBrush", 11, new Thickness(0, 2, 0, 0)));

        if (card.KnownNames.Count > 1)
            ContentPanel.Children.Add(Note(string.Format(Strings.AuthorCardAliasesFormat, string.Join(", ", card.KnownNames)),
                "TextSecondaryBrush", 12, new Thickness(0, 6, 0, 0)));

        if (card.IdentityTags.Count == 0 && !card.IsImplicit)
            ContentPanel.Children.Add(Note(Strings.AuthorCardNoAccountNotice, "TextSecondaryBrush", 11.5, new Thickness(0, 8, 0, 0)));

        if (!string.IsNullOrWhiteSpace(card.Description))
        {
            ContentPanel.Children.Add(new TextBlock
            {
                Text = card.Description,
                FontSize = 13,
                Margin = new Thickness(0, 14, 0, 0),
                TextWrapping = TextWrapping.Wrap,
            });
        }

        if (card.TwitterUrl is not null || card.YouTubeUrl is not null || card.TwitchUrl is not null)
        {
            var linksPanel = new StackPanel { Orientation = Orientation.Horizontal, Spacing = 10, Margin = new Thickness(0, 16, 0, 0) };
            if (card.TwitterUrl is { } twitterUrl) linksPanel.Children.Add(
                AuthorLinkButtonFactory.Build(this, twitterUrl, "IconTwitter", Strings.AuthorCardTwitterLabel, diameter: 30, iconSize: 15));
            if (card.YouTubeUrl is { } youTubeUrl) linksPanel.Children.Add(
                AuthorLinkButtonFactory.Build(this, youTubeUrl, "IconYoutube", Strings.AuthorCardYouTubeLabel, diameter: 30, iconSize: 15));
            if (card.TwitchUrl is { } twitchUrl) linksPanel.Children.Add(
                AuthorLinkButtonFactory.Build(this, twitchUrl, "IconTwitch", Strings.AuthorCardTwitchLabel, diameter: 30, iconSize: 15));
            ContentPanel.Children.Add(linksPanel);
        }

        AddStats(authorEntries);
        AddAssigned(authorEntries.Where(e => e.AssignedCardId == card.Id).ToList());
        AddAccountHints(_actions.AccountHints(card));
    }

    private const int MakesShown = 5;
    private const int MonthsShown = 24;

    /// <summary>Five numbers (three, then two), the duplicates line, the makes and the downloads by month</summary>
    private void AddStats(List<LiveryEntry> authorEntries)
    {
        var culture = AppLocalisationService.Culture;
        var row = _actions.Statistics?.Invoke(authorEntries);
        string N(int value) => value.ToString("N0", culture);

        // Six columns: the first row's three tiles take two each, the second row's two take three each
        var tiles = new Grid { Margin = new Thickness(0, 18, 0, 0), ColumnDefinitions = new ColumnDefinitions("*,*,*,*,*,*"), RowDefinitions = new RowDefinitions("Auto,Auto") };
        void Tile(int index, string value, string label, string? tooltip = null)
        {
            var tile = new Border
            {
                Background = this.GetThemeBrush("CardBrush"),
                BorderBrush = this.GetThemeBrush("BorderBrush2"),
                BorderThickness = new Thickness(1),
                CornerRadius = new CornerRadius(9),
                Padding = new Thickness(12, 9),
                Margin = new Thickness(0, index >= 3 ? 8 : 0, index is 2 or 4 ? 0 : 8, 0),
                Child = new StackPanel
                {
                    Spacing = 1,
                    Children =
                    {
                        new TextBlock { Text = value, FontSize = 18, FontWeight = FontWeight.Bold, TextTrimming = TextTrimming.CharacterEllipsis },
                        new TextBlock { Text = label, FontSize = 11.5, Foreground = this.GetThemeBrush("TextSecondaryBrush"), TextTrimming = TextTrimming.CharacterEllipsis },
                    },
                },
            };
            if (tooltip is not null) ToolTip.SetTip(tile, tooltip);
            bool firstRow = index < 3;
            Grid.SetColumn(tile, firstRow ? index * 2 : (index - 3) * 3);
            Grid.SetColumnSpan(tile, firstRow ? 2 : 3);
            Grid.SetRow(tile, firstRow ? 0 : 1);
            tiles.Children.Add(tile);
        }

        int liveries = row?.Liveries ?? authorEntries.Count;
        int favorites = row?.Favorites ?? authorEntries.Count(e => e.IsFavorite);
        Tile(0, N(liveries), Strings.AuthorCardStatLiveries);
        Tile(1, N(row?.Cars ?? authorEntries.Select(e => e.CarId).Distinct().Count()), Strings.AuthorCardStatCars);
        Tile(2, favorites == 0 ? "0" : $"{N(favorites)} · {StatisticsViewModel.Percent((double)favorites / Math.Max(1, liveries))}",
            Strings.AuthorCardStatFavorites);
        // The first and the latest download of his liveries in the collection
        Tile(3, row?.FirstDownload is { } first ? first.ToString("d", culture) : "—",
            Strings.AuthorCardStatFirstDownload, Strings.StatsColumnFirstDownloadTooltip);
        Tile(4, row?.LastDownload is { } last ? last.ToString("d", culture) : "—", Strings.AuthorCardStatLast,
            Strings.StatsColumnLastDownloadTooltip);
        ContentPanel.Children.Add(tiles);

        int duplicates = authorEntries.Count(e => e.IsDuplicate), possible = authorEntries.Count(e => e.IsPossibleDuplicate);
        if (duplicates + possible > 0)
            ContentPanel.Children.Add(Note(string.Format(Strings.AuthorCardDuplicatesLineFormat, N(duplicates), N(possible)),
                "TextSecondaryBrush", 11.5, new Thickness(2, 8, 0, 0)));

        var makes = LiveryStatistics.Breakdown(authorEntries, LiveryDimension.Manufacturer);
        if (makes.Rows.Count > 1)
        {
            ContentPanel.Children.Add(Header(Strings.StatsSectionManufacturers));
            int max = makes.Rows[0].Count;
            foreach (var make in makes.Rows.Take(MakesShown))
            {
                var line = new Grid { ColumnDefinitions = new ColumnDefinitions("3*,2*,Auto"), Margin = new Thickness(0, 3, 0, 0) };
                line.Children.Add(new TextBlock
                {
                    Text = string.IsNullOrWhiteSpace(make.Label) ? Strings.StatsUnknownValue : make.Label,
                    FontSize = 12.5, TextTrimming = TextTrimming.CharacterEllipsis, VerticalAlignment = VerticalAlignment.Center,
                    Margin = new Thickness(0, 0, 10, 0),
                });
                var bar = new ShareBar { Fraction = (double)make.Count / max, Height = 6, VerticalAlignment = VerticalAlignment.Center };
                Grid.SetColumn(bar, 1);
                line.Children.Add(bar);
                var count = new TextBlock
                {
                    Text = N(make.Count), FontSize = 12.5, FontWeight = FontWeight.SemiBold, MinWidth = 36,
                    TextAlignment = TextAlignment.Right, VerticalAlignment = VerticalAlignment.Center,
                };
                Grid.SetColumn(count, 2);
                line.Children.Add(count);
                ContentPanel.Children.Add(line);
            }
            if (makes.Rows.Count > MakesShown)
                ContentPanel.Children.Add(Note(string.Format(Strings.StatsMoreFormat, N(makes.Rows.Count - MakesShown)),
                    "TextSecondaryBrush", 11.5, new Thickness(0, 4, 0, 0)));
        }

        var months = LiveryStatistics.ByDownloadMonth(authorEntries);
        if (months.Count > 1)
        {
            ContentPanel.Children.Add(Header(Strings.AuthorCardMonthsTitle));
            var shown = months.Count > MonthsShown ? months.Skip(months.Count - MonthsShown).ToList() : months;
            ContentPanel.Children.Add(new MonthChart
            {
                Height = 110,
                UpSeries = ["accent"],
                Columns = [.. shown.Select(m => new ChartColumn(m.Month, [m.Count], [], null, false,
                    $"{m.Month.ToString("Y", culture)}\n{Strings.StatsTileLiveries}: {N(m.Count)}"))],
            });
        }
    }

    /// <summary>The liveries the user assigned to the card, each with a button that takes it out</summary>
    private void AddAssigned(List<LiveryEntry> assigned)
    {
        if (assigned.Count == 0) return;
        ContentPanel.Children.Add(Header(string.Format(Strings.AuthorCardAssignedSectionFormat, assigned.Count)));
        foreach (var entry in assigned.OrderBy(e => Services.AuthorInsights.Label(e), StringComparer.CurrentCultureIgnoreCase))
        {
            var row = new Grid { ColumnDefinitions = new ColumnDefinitions("*,Auto"), Margin = new Thickness(0, 4, 0, 0) };
            row.Children.Add(new TextBlock
            {
                Text = $"{Services.AuthorInsights.Label(entry)} — {entry.CarManufacturer} {entry.CarModelName}",
                FontSize = 12.5,
                VerticalAlignment = VerticalAlignment.Center,
                TextTrimming = TextTrimming.CharacterEllipsis,
            });
            var remove = new Button { Content = "✕", Padding = new Thickness(8, 2), Margin = new Thickness(8, 0, 0, 0) };
            remove.Classes.Add("secondary");
            ToolTip.SetTip(remove, Strings.AuthorCardRemoveAssignedTooltip);
            Grid.SetColumn(remove, 1);
            string? hash = entry.CLiveryHash;
            remove.Click += (_, _) =>
            {
                if (hash is null) return;
                _work.Run(async () =>
                {
                    await _actions.Unassign(hash);
                    Rebuild();
                }, "author card: unassign");
            };
            row.Children.Add(remove);
            ContentPanel.Children.Add(row);
        }
    }

    /// <summary>For a card without an account: accounts that may be the author's, to add or turn down</summary>
    private void AddAccountHints(IReadOnlyList<AuthorHintView> hints)
    {
        if (hints.Count == 0) return;
        ContentPanel.Children.Add(Header(Strings.AuthorCardAccountHintsHeader));
        foreach (var hint in hints)
        {
            var row = new StackPanel { Spacing = 4, Margin = new Thickness(0, 6, 0, 0) };
            row.Children.Add(new TextBlock { Text = hint.Text, FontSize = 12.5, TextWrapping = TextWrapping.Wrap });
            var buttons = new StackPanel { Orientation = Orientation.Horizontal, Spacing = 8 };
            var add = new Button { Content = Strings.AuthorCardAddAccountButton };
            add.Classes.Add("primary");
            var no = new Button { Content = Strings.AuthorCardNotThisButton };
            no.Classes.Add("secondary");
            string tag = hint.Hint.SubjectId[AuthorCard.ImplicitId("").Length..];
            add.Click += (_, _) => _work.Run(async () =>
            {
                if (await _actions.AddAccount(_card, tag) is { } saved) _card = saved;
                Rebuild();
            }, "author card: add account");
            no.Click += (_, _) => _work.Run(async () =>
            {
                await _actions.DismissHint(hint.Hint);
                Rebuild();
            }, "author card: dismiss hint");
            buttons.Children.Add(add);
            buttons.Children.Add(no);
            row.Children.Add(buttons);
            ContentPanel.Children.Add(row);
        }
    }

    private TextBlock Header(string text) => new()
    {
        Text = text,
        FontSize = 12.5,
        FontWeight = FontWeight.SemiBold,
        Margin = new Thickness(0, 18, 0, 2),
    };

    private TextBlock Note(string text, string brush, double size, Thickness margin) => new()
    {
        Text = text,
        FontSize = size,
        Margin = margin,
        TextWrapping = TextWrapping.Wrap,
        Foreground = this.GetThemeBrush(brush),
    };

    private void EditButton_Click(object? sender, Avalonia.Interactivity.RoutedEventArgs e) =>
        _work.Run(async () =>
        {
            if (await _actions.Edit(this, _card) is { } saved) _card = _actions.FindCard(saved.Id) ?? saved;
            Rebuild();
        }, "author card: edit");

    private void TitleBar_PointerPressed(object? sender, PointerPressedEventArgs e) => this.HandleTitleBarDrag(e);

    private void CloseButton_Click(object? sender, Avalonia.Interactivity.RoutedEventArgs e) => Close();
}
